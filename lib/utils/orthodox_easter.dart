/// Изчисляване на православния Великден (Пасха) по григориански календар.
///
/// Използва Meeus' Julian алгоритъм (Computus) за юлианската дата на Пасха,
/// после добавя 13 дни за разликата юлиански→григориански календар
/// (валидно за периода 1900-2099, в който разликата е постоянно 13 дни).
///
/// Връща `DateTime` (само дата, без час) на православния Великден за дадената
/// година в григориански календар.
///
/// Това е чиста функция — без странични ефекти, лесна за unit тест.
DateTime orthodoxEaster(int year) {
  // Meeus Julian algorithm — дава ден/месец на Пасха в ЮЛИАНСКИ календар.
  final a = year % 4;
  final b = year % 7;
  final c = year % 19;
  final d = (19 * c + 15) % 30;
  final e = (2 * a + 4 * b - d + 34) % 7;
  final month = (d + e + 114) ~/ 31; // 3 = март, 4 = април
  final day = ((d + e + 114) % 31) + 1;

  // Юлианската дата, изразена като григорианска: за 1900-2099 разликата е 13 дни.
  // Използваме календарни компоненти (day + 13), а НЕ Duration аритметика —
  // така избягваме дрейф при преминаване на лятно часово време (DST).
  // Dart нормализира преливането на деня коректно.
  return DateTime(year, month, day + 13);
}
